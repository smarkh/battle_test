"""Render a CaseRun as a Markdown document set."""

from collections import Counter
from datetime import datetime

from battle_test import grounding
from battle_test.citations import PLACEHOLDER
from battle_test.law_index import LawSection
from battle_test.pipeline import CaseRun, Document

def disclaimer(support_checked: bool = False) -> str:
    """`support_checked`: the "does it say that?" check ran on this case."""
    scope = (
        "for whether they exist and are in force. A model also compared each "
        "one with the passage citing it and marked those it doubts: that is a "
        "warning, not a guarantee, and an unmarked citation can still be wrong."
        if support_checked else
        "but only for whether they exist and are in force, not for whether "
        "they say what the brief claims."
    )
    return (
        "> **Draft for attorney review — not legal advice.** Generated by "
        "adversarial language models to stress-test a position. No winner is "
        "declared. Statute, rule and constitution citations have been checked "
        f"against a local copy of the law, {scope} Case law has "
        "**not** been checked. Every `[CITATION NEEDED: …]` placeholder and ⚠ mark "
        "needs attention before any of this is relied on."
    )


DISCLAIMER = disclaimer()

POSSIBLE_REFERENCES_NOTE = (
    "Sections the research found and picked as relevant, which no draft went "
    "on to cite. Each one exists and is in force in the law index. Whether it "
    "applies to this case has not been checked, and some will not: these are "
    "for the attorney to consider, not conclusions."
)
# Enough to see what a section is about. The source link has the rest.
POSSIBLE_EXCERPT_CHARS = 300

_STATUS_LABELS = {
    grounding.VERIFIED: "✅ in force",
    grounding.IN_FORCE_NOT_PROVIDED: "☑ in force, but the model never saw its text",
    grounding.AMBIGUOUS: "⚠ ambiguous (matches more than one section)",
    grounding.NOT_IN_FORCE: "❌ not in force",
    grounding.NOT_FOUND: "❌ not found",
    grounding.WRONG_JURISDICTION: "❌ other state's law",
}


def render_markdown(run: CaseRun, generated_at: datetime) -> str:
    meta = run.law_meta
    lines = [
        f"# Battle test — {run.state}",
        "",
        disclaimer(bool(run.checker_model)),
        "",
        f"- **Jurisdiction:** {run.state} and federal law",
        f"- **Law checked against:** statutes, court rules and constitutions current as of "
        f"{meta.get('snapshot_date', '?')} ({meta.get('attribution', 'Open US Law')}, "
        f"snapshot {meta.get('snapshot', '?')})",
        f"- **Generated:** {generated_at:%Y-%m-%d %H:%M}",
        f"- **Rounds:** {run.rounds}",
        f"- **Plaintiff model:** `{run.plaintiff_model}`",
        f"- **Defendant model:** `{run.defendant_model}`",
    ]
    if run.checker_model:
        lines.append(f"- **Citation checker model:** `{run.checker_model}`")
    if run.usage:
        lines.append(f"- **Model usage:** {usage_summary(run.usage, run.cost_usd)}")
    lines += _citation_summary(run)
    for doc in run.documents:
        source = "LLM-generated" if doc.generated else "user-supplied"
        lines += ["", "---", "", f"## {doc.title}", "", f"*{doc.role.title()} · {source}*", "", doc.text]
    lines += _possible_references(run)
    lines += _appendix(run)
    return "\n".join(lines) + "\n"


def usage_summary(usage: dict[str, dict[str, int]], cost_usd: float | None) -> str:
    calls, tokens_in, tokens_out = (sum(u[k] for u in usage.values())
                                    for k in ("calls", "input_tokens", "output_tokens"))
    cost = "no price set for this model" if cost_usd is None else f"estimated cost ${cost_usd:.3f}"
    return f"{calls} calls, {tokens_in:,} tokens in, {tokens_out:,} out, {cost}"


def _citation_summary(run: CaseRun) -> list[str]:
    lines = [
        "", "## Citation check", "",
        "| Document | ✅ in force | ☑ in force, not shown to model | ❌ problems "
        "| ⚠ may not support | ⚠ ambiguous | unchecked lines | `[CITATION NEEDED]` |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for doc in run.documents:
        counts = Counter(c.status for c in doc.checks)
        problems = sum(counts[s] for s in grounding.PROBLEM_STATUSES)
        placeholders = sum(1 for m in PLACEHOLDER.finditer(doc.text) if m.group().startswith("[CITATION"))
        doubted = sum(c.support in grounding.DOUBTED for c in doc.checks) if run.checker_model else "–"
        lines.append(
            f"| {doc.title} | {counts[grounding.VERIFIED]} | {counts[grounding.IN_FORCE_NOT_PROVIDED]} "
            f"| {problems} | {doubted} | {counts[grounding.AMBIGUOUS]} | {len(doc.unchecked)} | {placeholders} |"
        )
    for doc in run.documents:
        lines += _document_details(doc)
    return lines


def _document_details(doc: Document) -> list[str]:
    notable = [c for c in doc.checks if c.status != grounding.VERIFIED or c.support in grounding.DOUBTED]
    if not notable and not doc.unchecked:
        return []
    lines = ["", f"**{doc.title}**", ""]
    for c in notable:
        matched = f" → `{c.section.citation}`" if c.section else ""
        if c.status != grounding.VERIFIED:
            lines.append(f"- {_STATUS_LABELS[c.status]}: `{c.text}`{matched}")
        if c.support in grounding.DOUBTED:
            lines.append(f"- ⚠ {grounding.SUPPORT_LABELS[c.support]}: `{c.text}`. "
                         f"Checker's note: {c.support_reason or 'none given'}")
    for snippet in doc.unchecked:
        lines.append(f"- ⚠ not checked (case law, or a format the checker can't read): {snippet}")
    return lines


def _source(s: LawSection) -> str:
    return f" — [source]({s.source_url})" if s.source_url else " — ⚠ no official source URL"


def possible_references(run: CaseRun) -> list[LawSection]:
    """Sections quoted to the models that no document cites. They come from
    the law index, never from a model's memory."""
    cited = {c.section.citation for doc in run.documents for c in doc.checks
             if c.section is not None and c.status in grounding.CITED_STATUSES}
    return list({s.citation: s for doc in run.documents for s in doc.authorities
                 if s.citation not in cited}.values())


def _possible_references(run: CaseRun) -> list[str]:
    possible = possible_references(run)
    if not possible:
        return []
    lines = ["", "---", "", "## Possible references", "", f"*{POSSIBLE_REFERENCES_NOTE}*", ""]
    for s in possible:
        lines.append(f"- `{s.citation}` {s.section_title}{_source(s)}  \n"
                     f"  {grounding.excerpt(s.text, POSSIBLE_EXCERPT_CHARS, ' …')}")
    return lines


def _appendix(run: CaseRun) -> list[str]:
    lines = ["", "---", "", "## Appendix: authorities and research", ""]
    for role, queries in run.research.items():
        lines.append(f"**{role.title()} research queries:** " + "; ".join(f"“{q}”" for q in queries))
        lines.append("")
    seen: dict[str, list[str]] = {}
    sections = {}
    for doc in run.documents:
        for s in doc.authorities:
            seen.setdefault(s.citation, []).append(doc.title)
            sections[s.citation] = s
    if seen:
        lines += ["**Authorities quoted to the models:**", ""]
        for citation, titles in seen.items():
            s = sections[citation]
            lines.append(f"- `{citation}` {s.section_title}{_source(s)}  \n  *given for: {', '.join(titles)}*")
    return lines
